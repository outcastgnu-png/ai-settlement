// Writes test/vectors/sdk-parity.json: what the TypeScript kit produces for
// fixed inputs, so the Python SDK can be checked byte for byte against it.
// The keys come from all-zero and all-one entropy; they are vector keys only
// and are never funded. Run with: npx tsx test/vectors/make-sdk-vectors.ts
import { writeFileSync } from "node:fs";
import { deriveAddress, sign } from "ripple-keypairs";
import { Wallet, type ECDSA } from "xrpl";
import { canonicalJson, replayKey, sha256Hex, signPayload } from "../../src/auth.js";
import { toCondition, toFulfillment } from "../../src/condition.js";

const hexOf = (text: string) => Buffer.from(text, "utf8").toString("hex").toUpperCase();

const secrets = ["00".repeat(32), "01".repeat(32), "ff".repeat(32), sha256Hex("vector secret")];
const conditions = secrets.map((s) => ({
  secret: s, condition: toCondition(Buffer.from(s, "hex")), fulfillment: toFulfillment(Buffer.from(s, "hex")),
}));

const keys = [
  { algorithm: "ed25519", entropy: "00".repeat(16) },
  { algorithm: "secp256k1", entropy: "00".repeat(16) },
  { algorithm: "ed25519", entropy: "11".repeat(16) },
  { algorithm: "secp256k1", entropy: "11".repeat(16) },
];
const wallet = (k: { algorithm: string; entropy: string }) =>
  Wallet.fromEntropy(Buffer.from(k.entropy, "hex"), { algorithm: k.algorithm as ECDSA });

const content = "the work\n";
const requests = keys.flatMap((k) => {
  const w = wallet(k);
  return [
    { action: "deliver", jobId: "6f7c1e9a-0000-4000-8000-000000000001", timestamp: 1_761_000_000_000, payloadHash: sha256Hex(content) },
    { action: "verify", jobId: "6f7c1e9a-0000-4000-8000-000000000001", timestamp: 1_761_000_000_123, payloadHash: "" },
  ].map((r) => {
    const message = hexOf(`${r.action}|${r.jobId}|${r.timestamp}|${r.payloadHash}`);
    return {
      ...k, address: w.address, publicKey: w.publicKey, ...r, message,
      signature: sign(message, w.privateKey),
      replayKey: replayKey(w.publicKey, r.action, r.jobId, r.timestamp, r.payloadHash),
    };
  });
});

const verdictKey = wallet(keys[0]);
const verdictBody = {
  jobId: "6f7c1e9a-0000-4000-8000-000000000001", verdict: "pass",
  checks: [{ type: "sha256-match", pass: true, detail: "sha256 matches" }, { type: "max-latency", pass: true, detail: "délivré in 12 ms ✓" }],
  evidenceHash: sha256Hex(content), condition: conditions[3].condition, provider: wallet(keys[1]).address,
  oracle: verdictKey.address, publicKey: verdictKey.publicKey, issuedAt: 1_761_000_000_456,
};
const verdict = {
  algorithm: "ed25519", entropy: keys[0].entropy, body: verdictBody, canonical: canonicalJson(verdictBody),
  signature: signPayload(verdictBody, verdictKey),
};

if (deriveAddress(verdictKey.publicKey) !== verdictKey.address) throw new Error("address mismatch");
const out = { note: "Generated by test/vectors/make-sdk-vectors.ts. Vector keys only, never funded.", content, contentSha256: sha256Hex(content), conditions, requests, verdict };
writeFileSync(new URL("./sdk-parity.json", import.meta.url), `${JSON.stringify(out, null, 2)}\n`);
console.log(`wrote ${conditions.length} conditions, ${requests.length} signed requests, 1 verdict`);
